import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const run = (command, args) =>
  execFileSync(command, args, { encoding: "utf8" });
const licenseName =
  /^(licen[cs]e|copying|copyright|notice|patents)([._-].*)?$/i;
const texts = new Map();
const packages = new Map();
const goBuilder = readFileSync("deploy/Dockerfile", "utf8").match(
  /^FROM --platform=\$BUILDPLATFORM golang:([^@\s]+)@(sha256:[a-f0-9]{64}) AS go-build$/m,
);
assert.ok(
  goBuilder,
  "The container CA bundle must come from a pinned Go builder",
);
const caNotice = readFileSync("licenses/mozilla-ca-certificates.txt", "utf8");
assert.ok(
  caNotice.includes(`golang:${goBuilder[1]}@${goBuilder[2]}`),
  "Review the CA bundle provenance when the builder image changes",
);
function retain(text) {
  // Normalize formatting only; all copyright and license wording is retained.
  text = text
    .replaceAll("\r\n", "\n")
    .replace(/[ \t]+$/gm, "")
    .trim();
  assert.ok(text.length > 20, "License notices must not be empty");
  if (!texts.has(text)) texts.set(text, `license-${texts.size + 1}`);
  return texts.get(text);
}
function licenseFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && licenseName.test(entry.name))
    .map((entry) => entry.name)
    .sort();
}
function add(name, version, directory) {
  let files = licenseFiles(directory).map((file) => join(directory, file));
  if (
    !files.length &&
    name === "react-remove-scroll-bar" &&
    version === "2.3.8"
  )
    files = ["licenses/react-remove-scroll-bar-2.3.8.txt"];
  assert.ok(files.length, `Missing license for ${name}@${version}`);
  const ids = files.map((file) => retain(readFileSync(file, "utf8")));
  packages.set(`${name}@${version}`, { name, version, ids });
}

const goRoot = run("go", ["env", "GOROOT"]).trim();
const goVersion = run("go", ["env", "GOVERSION"]).trim();
add("Go standard library and runtime", goVersion, goRoot);
const goPackages = run("go", [
  "list",
  "-deps",
  "-f",
  "{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}|{{.Dir}}{{else if .Standard}}std|||{{.Dir}}{{end}}",
  "./cmd/nexa-home",
]);
for (const row of goPackages.trim().split("\n")) {
  const [name, version, root, directory] = row.split("|");
  if (name === "nexa-home") continue;
  if (name !== "std" && !packages.has(`${name}@${version}`))
    add(name, version, root);
  // Preserve any additional notices in imported package subdirectories, including
  // standard-library implementations with separately retained upstream licenses.
  for (
    let current = directory;
    current && current !== (root || goRoot);
    current = dirname(current)
  ) {
    assert.ok(
      current.startsWith((root || goRoot) + "/"),
      "License search stays inside its module",
    );
    for (const file of licenseFiles(current))
      retain(readFileSync(join(current, file), "utf8"));
  }
}
const npmDirectories = run("npm", [
  "ls",
  "--workspace=@nexa-home/web",
  "--omit=dev",
  "--all",
  "--parseable",
])
  .trim()
  .split("\n");
// These build dependencies contribute actual CSS or browser bootstrap code.
npmDirectories.push(
  ...["tailwindcss", "tw-animate-css", "vite"].map((name) =>
    resolve("node_modules", name),
  ),
);
for (const directory of npmDirectories) {
  const info = JSON.parse(
    readFileSync(join(directory, "package.json"), "utf8"),
  );
  if (["nexa-home", "@nexa-home/web"].includes(info.name)) continue;
  add(info.name, info.version, directory);
}
packages.set("shadcn/ui", {
  name: "shadcn/ui copied primitives",
  version: "nova templates",
  ids: [retain(readFileSync("licenses/shadcn-ui.txt", "utf8"))],
});
packages.set("container-ca-bundle", {
  name: "Alpine Mozilla CA certificate bundle (container only)",
  version: `${goBuilder[1]}@${goBuilder[2]}`,
  ids: [retain(caNotice), retain(readFileSync("licenses/MPL-2.0.txt", "utf8"))],
});

const rows = [...packages.values()]
  .sort((a, b) => a.name.localeCompare(b.name, "en"))
  .map(
    ({ name, version, ids }) =>
      `| ${name} | ${version} | ${ids.map((id) => `[text](#${id})`).join(", ")} |`,
  );
const sections = [...texts].map(
  ([text, id]) => `## ${id}\n\n~~~~text\n${text}\n~~~~\n`,
);
const output = `# Third-party notices\n\nGenerated by \`npm run notices\` from locked dependencies and the pinned container builder. Preserve this file and LICENSE when distributing Nexa Home or its container image. Third-party components are not relicensed by Nexa Home's MIT license.\n\nThe inventory includes the complete frontend production dependency closure, CSS/bootstrap contributors, copied shadcn/ui primitives, Go runtime and imported Go modules, and the container's CA certificate bundle. Some packages are types-only or removed by production tree-shaking; their inclusion does not imply runtime execution. SQLite itself is in the public domain; its Go driver and supporting modules retain the notices below. Build-only Node, compiler, test, scanning and emulation tools are not shipped in the runtime image.\n\n| Component | Version | License / notice |\n| --- | --- | --- |\n${rows.join("\n")}\n\n${sections.join("\n")}`;
const target = "THIRD_PARTY_NOTICES.md";
const previous = existsSync(target) ? readFileSync(target, "utf8") : "";
if (process.argv.includes("--check")) {
  assert.ok(
    previous === output,
    "Third-party notices drifted; run npm run notices",
  );
  console.log(
    `Third-party notices match ${packages.size} components and ${texts.size} retained texts.`,
  );
} else {
  writeFileSync(target, output);
  console.log(
    `Wrote notices for ${packages.size} components and ${texts.size} retained texts.`,
  );
}
